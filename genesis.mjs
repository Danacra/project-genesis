import { SurvivorData,NPCData,ColonyData,MaterialData,GearData,ToolData,ComponentData,ConsumableData,ContainerData } from './module/models.mjs';
import { GenesisActorSheet, GenesisItemSheet } from './module/sheets.mjs';
import { initializeLogistics, advanceDay } from './module/logistics.mjs';
import { ABILITIES, SKILLS } from './module/rules.mjs';
import { initializeResearch, requestResearch, TECHNOLOGIES } from './module/research.mjs';
import { validateCatalog } from './module/research-rules.mjs';
import { initializeIndustry, requestIndustry, RECIPES, BUILDINGS } from './module/industry.mjs';
import { validateIndustryCatalog } from './module/industry-data.mjs';
import { validateIndustryState } from './module/industry-rules.mjs';
import { startPlacement,cancelPlacement } from './module/map-placement.mjs';
import { BUILDING_FOOTPRINTS } from './module/map-rules.mjs';
import {initializeNetworks,requestNetwork,NETWORK_TYPES} from './module/networks.mjs';
import {startNetworkDrawing,cancelNetworkDrawing} from './module/network-drawing.mjs';
import {initializeCrew,requestCrew,RESOURCE_NODES} from './module/crew.mjs';
import {startResourcePlacement,stopResourcePlacement} from './module/crew-placement.mjs';
const ID = 'project-genesis';
Hooks.once('init',()=>{
  CONFIG.Actor.dataModels.survivor=SurvivorData;
  CONFIG.Actor.dataModels.npc=NPCData;
  CONFIG.Actor.dataModels.colony=ColonyData;
  CONFIG.Item.dataModels.material=MaterialData;
  CONFIG.Item.dataModels.gear=GearData;
  CONFIG.Item.dataModels.tool=ToolData;
  CONFIG.Item.dataModels.component=ComponentData;
  CONFIG.Item.dataModels.consumable=ConsumableData;
  CONFIG.Item.dataModels.container=ContainerData;
  const sheetConfig=foundry.applications.apps.DocumentSheetConfig;
  sheetConfig.registerSheet(Actor,ID,GenesisActorSheet,{types:['survivor','npc','colony'],makeDefault:true,label:'PROJECT GENESIS — лист'});
  sheetConfig.registerSheet(Item,ID,GenesisItemSheet,{types:['material','gear','tool','component','consumable','container'],makeDefault:true,label:'PROJECT GENESIS — предмет'});
  game.settings.register(ID,'worldDay',{name:'День экспедиции',scope:'world',config:false,type:Number,default:1});
  game.settings.register(ID,'logisticsJournal',{name:'Журнал логистики',scope:'world',config:false,type:Object,default:{entries:[],processed:[]}});
  CONFIG.projectGenesis={abilities:ABILITIES,skills:SKILLS,technologies:TECHNOLOGIES};
  validateCatalog();
  validateIndustryCatalog();
  validateIndustryState();
});
Hooks.once('ready',()=>{
  initializeLogistics();
  initializeResearch();
  initializeIndustry();
  initializeNetworks();
  initializeCrew();
  game.projectGenesis={advanceDay,requestResearch,requestIndustry,technologies:TECHNOLOGIES,recipes:RECIPES,buildings:BUILDINGS,buildingFootprints:BUILDING_FOOTPRINTS,startPlacement,cancelPlacement,startNetworkDrawing,cancelNetworkDrawing,requestNetwork,networkTypes:NETWORK_TYPES,requestCrew,resourceNodes:RESOURCE_NODES,startResourcePlacement,stopResourcePlacement};
  console.info('PROJECT GENESIS v0.8.1 ready');
});
